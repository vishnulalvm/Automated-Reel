"""Moves files between the user's Reel folder (reel.config.json) and the project.

  reel.py in             copy new scripts from the input folder to episodes/<slug>/ and
                         print the episode folders that have no video yet
  reel.py assets         copy the Assets folder into the video project
  reel.py out <slug>     copy the video, caption and thumbnail to the output folder
  reel.py verify <slug>  the human has watched and accepted it: move the input script to its Archive
  reel.py posted <slug>  after publishing: move the output files to the output Archive
  reel.py status         one line per episode
"""
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CFG = json.loads((ROOT / "reel.config.json").read_text())
F = CFG["folders"]
BASE = Path(F["root"])
INPUT, OUTPUT, ASSETS = BASE / F["input"], BASE / F["output"], BASE / F["assets"]
EPISODES = ROOT / "episodes"
PUBLIC_ASSETS = ROOT / "video" / "public" / "assets"
OUT_FILES = {"final.mp4": "{slug}.mp4", "caption.txt": "{slug}-caption.txt", "thumbnail.png": "{slug}-thumbnail.png"}


def archive(folder: Path) -> Path:
    a = folder / F["archive"]
    a.mkdir(parents=True, exist_ok=True)
    return a


def slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def scripts():
    """Scripts waiting in the input folder. Names starting with _ or . are ignored (e.g. _template.txt)."""
    if not INPUT.is_dir():
        sys.exit(f"Input folder not found: {INPUT}")
    return sorted(
        p for p in INPUT.iterdir()
        if p.is_file() and p.suffix.lower() in (".md", ".txt") and p.name[0] not in "._"
    )


def cmd_in():
    for src in scripts():
        slug = slugify(src.stem)
        if not slug:
            continue
        ep = EPISODES / slug
        ep.mkdir(parents=True, exist_ok=True)
        story = ep / f"story{src.suffix.lower()}"
        if not story.exists() or story.read_bytes() != src.read_bytes():
            shutil.copy2(src, story)  # new or edited script: rebuild
            for stale in ("final.mp4", "VERIFIED"):
                (ep / stale).unlink(missing_ok=True)
        (ep / "source.txt").write_text(src.name)
        if not (ep / "final.mp4").exists():
            print(f"episodes/{slug}")


def cmd_assets():
    names = []
    if ASSETS.is_dir():
        PUBLIC_ASSETS.mkdir(parents=True, exist_ok=True)
        for p in sorted(ASSETS.iterdir()):
            if p.is_file() and p.name[0] != ".":
                shutil.copy2(p, PUBLIC_ASSETS / p.name)
                names.append(p.name)
    if PUBLIC_ASSETS.is_dir():
        for p in PUBLIC_ASSETS.iterdir():
            if p.name not in names:
                p.unlink()  # removed from Assets (or moved to its Archive)
    (ROOT / "video" / "src" / "assets.gen.ts").write_text(
        "// Generated by scripts/reel.py assets. Files in the user's Assets folder, usable as staticFile(`assets/<name>`).\n"
        f"export const ASSETS: string[] = {json.dumps(names)};\n"
    )
    print("\n".join(names) if names else "(no assets)")


def cmd_out(slug):
    ep = EPISODES / slug
    if not (ep / "final.mp4").exists():
        sys.exit(f"No final.mp4 in {ep}")
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for name, pattern in OUT_FILES.items():
        if (ep / name).exists():
            dest = OUTPUT / pattern.format(slug=slug)
            shutil.copy2(ep / name, dest)
            print(dest)


def cmd_verify(slug):
    ep = EPISODES / slug
    if not (ep / "final.mp4").exists():
        sys.exit(f"{slug} has no video yet")
    src = INPUT / (ep / "source.txt").read_text().strip() if (ep / "source.txt").exists() else None
    if src and src.exists():
        dest = archive(INPUT) / src.name
        shutil.move(str(src), dest)
        print(f"archived script: {dest}")
    else:
        print("input script already archived or not found")
    (ep / "VERIFIED").touch()


def cmd_posted(slug):
    dest_dir = archive(OUTPUT)
    for pattern in OUT_FILES.values():
        p = OUTPUT / pattern.format(slug=slug)
        if p.exists():
            shutil.move(str(p), dest_dir / p.name)
            print(f"archived output: {dest_dir / p.name}")


def cmd_status():
    for ep in sorted(p for p in EPISODES.iterdir() if p.is_dir()) if EPISODES.is_dir() else []:
        state = [s for s, f in (("built", "final.mp4"), ("verified", "VERIFIED"), ("approved", "APPROVED"), ("posted", "PUBLISHED")) if (ep / f).exists()]
        print(f"{ep.name:28} {', '.join(state) or 'not built'}")
    waiting = [p.name for p in scripts()]
    print(f"input folder: {', '.join(waiting) or 'empty'}")


if __name__ == "__main__":
    for d in (INPUT, OUTPUT, ASSETS):
        if d.is_dir():
            archive(d)
    cmd, args = (sys.argv[1] if len(sys.argv) > 1 else ""), sys.argv[2:]
    one = {"out": cmd_out, "verify": cmd_verify, "posted": cmd_posted}
    if cmd in one and args:
        one[cmd](Path(args[0].rstrip("/")).name)
    elif cmd in ("in", "assets", "status"):
        {"in": cmd_in, "assets": cmd_assets, "status": cmd_status}[cmd]()
    else:
        sys.exit(__doc__)
